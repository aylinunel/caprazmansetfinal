"""Blind precision and estimated recall of the behavioural review, from human gold."""
from validation.feedback.stats import wilson_lower


def _scope() -> dict:
    return {"tp": 0, "fp": 0, "found_unflagged": 0, "missed_est": 0.0}


def _finish(s: dict) -> dict:
    shown = s["tp"] + s["fp"]
    s["precision"] = s["tp"] / shown if shown else None
    s["precision_lower"] = wilson_lower(s["tp"], shown)
    found = s["tp"] + s["missed_est"]
    s["recall_outside_selection_est"] = s["tp"] / found if found else None
    return s


def measure(gold: dict, key: dict) -> dict:
    """gold: item -> "yes"/"no" (unsure and disputed items already left out)."""
    unflagged = key.get("_unflagged", {})
    overall, cards = _scope(), {}
    for item, meta in key.items():
        if item == "_unflagged" or gold.get(item) not in ("yes", "no"):
            continue
        yes = gold[item] == "yes"
        for s in (overall, cards.setdefault(meta["card"], _scope())):
            if meta["ai_shown"]:
                s["tp" if yes else "fp"] += 1
            elif yes:
                u = unflagged.get(meta["event"])
                s["found_unflagged"] += 1
                s["missed_est"] += u["total"] / u["sampled"] if u and u["sampled"] else 1.0
    return {"overall": _finish(overall), "cards": {c: _finish(s) for c, s in sorted(cards.items())}}


def as_card_stats(m: dict) -> dict:
    return {c: {"reviewed": s["tp"] + s["fp"], "kept": s["tp"], "rejected": s["fp"],
                "precision": s["precision"], "lower": s["precision_lower"]} for c, s in m["cards"].items()}


def _f(x):
    return "veri yok" if x is None else f"{x:.3f}"


def _present_line(present: dict | None) -> list:
    if present is None:
        return []
    a = present["alpha"]
    return [f"present alfa: {'veri yok' if a is None else f'{a:.3f}'}; "
            f"{'kullanılabilir' if present['usable'] else 'henüz kullanılabilir değil (not usable yet)'}", ""]


def report(m: dict, disputed: int = 0, present: dict | None = None) -> str:
    lines = ["<!-- generated by `python -m validation.answerkey behaviour-eval` -->",
             "# Davranış incelemesi: kör insan altın standardına karşı", "",
             f"Uyuşmazlık nedeniyle sayılmayan öğe: {disputed}", "",
             *_present_line(present),
             "Bu paketteki yapay zekâ bulguları herkese açık olay sayfalarında da görünür; körlük yalnızca masanın içinde geçerlidir.", "",
             "Seçim dışı tahmini duyarlılık yalnızca seçicinin seçmediği kartlardan örneklenir; seçilip gözden geçirmede "
             "reddedilen kartlar sayılmaz.", "",
             "| kapsam | doğru (tp) | yanlış (fp) | bulunan kaçırılan | tahmini kaçırılan | kesinlik | alt sınır | seçim dışı tahmini duyarlılık |",
             "|---|---|---|---|---|---|---|---|"]
    for name, s in [("tümü", m["overall"])] + list(m["cards"].items()):
        lines.append(f"| {name} | {s['tp']} | {s['fp']} | {s['found_unflagged']} | {s['missed_est']:.1f} | "
                     f"{_f(s['precision'])} | {_f(s['precision_lower'])} | {_f(s['recall_outside_selection_est'])} |")
    return "\n".join(lines) + "\n"
