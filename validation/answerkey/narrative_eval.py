"""Scores the narrative coding agent against the human-coded weeks, row by row."""
import json
from pathlib import Path

from .agreement import krippendorff_alpha, percent_agreement
from .codebook import HUMAN_STATUSES, blame_level, frame_category


def _measure(pairs: list[tuple[str, str]]) -> dict:
    units = [list(p) for p in pairs]
    return {"n": len(pairs), "agreement": percent_agreement(units), "alpha": krippendorff_alpha(units)}


def compare(agent: dict[str, dict], core: dict, codebook: dict) -> dict:
    """Pairs are the rows both sides coded, matched on (N key, outlet slug); the agent's other rows are ignored."""
    blame, frame, unmapped, events = [], [], 0, 0
    for key, entry in core["N"].items():
        if entry.get("status") not in HUMAN_STATUSES or key not in agent:
            continue
        events += 1
        theirs = {r.get("s"): r for r in agent[key].get("rows", [])}
        for r in entry["rows"]:
            a = theirs.get(r["s"])
            if a is None:
                continue
            blame.append((blame_level(r.get("blame")), blame_level(a.get("blame"))))
            frame.append((frame_category(r.get("frame"), codebook), frame_category(a.get("frame"), codebook)))
            f = (a.get("frame") or "").strip()
            unmapped += bool(f) and f not in codebook["frames"]
    return {"events": events, "blame_level": _measure(blame), "frame_category": _measure(frame),
            "unmapped_frames": unmapped, "codebook_approved": bool(codebook.get("approved"))}


def read_coded(folder: Path) -> dict[str, dict]:
    return {p.stem: json.loads(p.read_text(encoding="utf-8")) for p in sorted(Path(folder).glob("*.json"))}


def _fmt(x) -> str:
    return "—" if x is None else f"{x:.3f}"


def report(r: dict) -> str:
    lines = ["<!-- generated by `python -m validation.answerkey narrative-eval` -->",
             "# Anlatı ajanı ile insan kodlaması", "",
             f"Karşılaştırılan olay: {r['events']}. Eşleşmeyen kurum satırları sayılmaz.", ""]
    if not r["codebook_approved"]:
        lines += ["Kod defteri henüz onaylanmadı.", ""]
    lines += ["| boyut | satır | yüzde uyum | alfa |", "|---|---|---|---|"]
    for name, label in (("blame_level", "Sorumluluk düzeyi"), ("frame_category", "Çerçeve kategorisi")):
        m = r[name]
        lines.append(f"| {label} | {m['n']} | {_fmt(m['agreement'])} | {_fmt(m['alpha'])} |")
    lines += ["", f"Kod defterinde karşılığı olmayan ajan çerçevesi: {r['unmapped_frames']}", ""]
    return "\n".join(lines)
